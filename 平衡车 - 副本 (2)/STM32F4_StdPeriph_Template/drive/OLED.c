/* ===================== 像素与图形 ===================== */

void OLED_SetPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) {
        return;
    }
    if (color == OLED_COLOR_WHITE) {
        OLED_GRAM[y >> 3][x] |= (uint8_t)(1U << (y & 0x07));
    } else {
        OLED_GRAM[y >> 3][x] &= (uint8_t)~(1U << (y & 0x07));
    }
}

/* 修复：使用 int16_t 内部坐标，避免 uint8_t 下溢导致的死循环/飞线 */
void OLED_DrawLine(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color)
{
    int16_t x = (int16_t)x0;
    int16_t y = (int16_t)y0;
    int16_t x_end = (int16_t)x1;
    int16_t y_end = (int16_t)y1;
    int16_t dx = (x_end > x) ? (x_end - x) : (x - x_end);
    int16_t dy = (y_end > y) ? (y_end - y) : (y - y_end);
    int16_t sx = (x < x_end) ? 1 : -1;
    int16_t sy = (y < y_end) ? 1 : -1;
    int16_t err = dx - dy;

    for (;;) {
        if (x >= 0 && x < OLED_WIDTH && y >= 0 && y < OLED_HEIGHT) {
            OLED_SetPixel((uint8_t)x, (uint8_t)y, color);
        }
        if (x == x_end && y == y_end) {
            break;
        }
        int16_t e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x += sx;
        }
        if (e2 < dx) {
            err += dx;
            y += sy;
        }
    }
}

void OLED_DrawRectangle(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color)
{
    uint8_t x, y, t;

    if (x0 > x1) { t = x0; x0 = x1; x1 = t; }
    if (y0 > y1) { t = y0; y0 = y1; y1 = t; }

    for (x = x0; x <= x1; x++) {
        OLED_SetPixel(x, y0, color);
        OLED_SetPixel(x, y1, color);
    }
    for (y = y0; y <= y1; y++) {
        OLED_SetPixel(x0, y, color);
        OLED_SetPixel(x1, y, color);
    }
}

void OLED_DrawFillRectangle(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color)
{
    uint8_t x, y, t;

    if (x0 > x1) { t = x0; x0 = x1; x1 = t; }
    if (y0 > y1) { t = y0; y0 = y1; y1 = t; }

    for (y = y0; y <= y1; y++) {
        for (x = x0; x <= x1; x++) {
            OLED_SetPixel(x, y, color);
        }
    }
}

void OLED_DrawBMP(uint8_t x0, uint8_t y0_page,
                  uint8_t x1, uint8_t y1_page,
                  const uint8_t *bmp)
{
    uint8_t x, y;
    uint16_t index = 0;

    if (x1 > OLED_WIDTH)  x1 = OLED_WIDTH;
    if (y1_page > OLED_PAGES) y1_page = OLED_PAGES;

    for (y = y0_page; y < y1_page; y++) {
        for (x = x0; x < x1; x++) {
            if (x < OLED_WIDTH && y < OLED_PAGES) {
                OLED_GRAM[y][x] = bmp[index];
            }
            index++;
        }
    }
}

/* ===================== 6x8 字体（写 GRAM） ===================== */

void OLED_ShowChar(uint8_t x, uint8_t y_page, char chr, uint8_t mode)
{
    uint8_t c = (uint8_t)(chr - ' ');
    uint8_t i;
    uint8_t d;

    if (c >= 96) return;
    if ((x + 6) > OLED_WIDTH || y_page >= OLED_PAGES) return;

    for (i = 0; i < 6; i++) {
        d = OLED_F6x8[c][i];
        if (mode == OLED_MODE_REVERSE) d = (uint8_t)~d;
        OLED_GRAM[y_page][x + i] = d;
    }
}

void OLED_ShowString(uint8_t x, uint8_t y_page, const char *str, uint8_t mode)
{
    while (*str != '\0') {
        OLED_ShowChar(x, y_page, *str, mode);
        x += 6;
        if ((x + 6) > OLED_WIDTH) break;
        str++;
    }
}

/* 修复：使用 uint32_t 处理绝对值，避免 INT32_MIN 溢出 */
void OLED_ShowNum(uint8_t x, uint8_t y_page, int32_t num, uint8_t mode)
{
    char buf[12];
    uint8_t i = 0;
    uint32_t n;

    if (num < 0) {
        OLED_ShowChar(x, y_page, '-', mode);
        x += 6;
        n = (uint32_t)(-(num + 1)) + 1U;
    } else if (num == 0) {
        OLED_ShowChar(x, y_page, '0', mode);
        return;
    } else {
        n = (uint32_t)num;
    }

    while (n > 0) {
        buf[i++] = (char)('0' + (n % 10));
        n /= 10;
    }

    while (i > 0) {
        OLED_ShowChar(x, y_page, buf[--i], mode);
        x += 6;
        if ((x + 6) > OLED_WIDTH) break;
    }
}

/* ===================== 8x16 字体（写 GRAM） ===================== */

static void OLED_ShowChar8x16(uint8_t x, uint8_t y_page, char chr, uint8_t mode)
{
    uint8_t c = (uint8_t)(chr - ' ');
    uint8_t i;
    uint8_t d;

    if (c >= 96) return;
    if ((x + 8) > OLED_WIDTH || (y_page + 1) >= OLED_PAGES) return;

    for (i = 0; i < 8; i++) {
        d = OLED_F8x16[c][i];
        if (mode == OLED_MODE_REVERSE) d = (uint8_t)~d;
        OLED_GRAM[y_page][x + i] = d;
    }
    for (i = 0; i < 8; i++) {
        d = OLED_F8x16[c][i + 8];
        if (mode == OLED_MODE_REVERSE) d = (uint8_t)~d;
        OLED_GRAM[y_page + 1][x + i] = d;
    }
}

/* ===================== 扩展接口（Ex = 可选字号） ===================== */

void OLED_ShowCharEx(uint8_t x, uint8_t y_page, char chr, uint8_t size, uint8_t mode)
{
    if (size == OLED_FONT_8X16) {
        OLED_ShowChar8x16(x, y_page, chr, mode);
    } else {
        OLED_ShowChar(x, y_page, chr, mode);
    }
}

void OLED_ShowStringEx(uint8_t x, uint8_t y_page, const char *str, uint8_t size, uint8_t mode)
{
    uint8_t step = (size == OLED_FONT_8X16) ? 8 : 6;

    while (*str != '\0') {
        OLED_ShowCharEx(x, y_page, *str, size, mode);
        x += step;
        if ((x + step) > OLED_WIDTH) break;
        str++;
    }
}

/* ===================== 行列坐标接口（At = At position） ===================== */

void OLED_ShowCharAt(uint8_t row, uint8_t col, char chr, uint8_t size, uint8_t mode)
{
    uint8_t x = (size == OLED_FONT_8X16) ? (col * 8) : (col * 6);
    uint8_t y_page = row;
    OLED_ShowCharEx(x, y_page, chr, size, mode);
}

void OLED_ShowStringAt(uint8_t row, uint8_t col, const char *str, uint8_t size, uint8_t mode)
{
    uint8_t step = (size == OLED_FONT_8X16) ? 8 : 6;
    uint8_t x = (size == OLED_FONT_8X16) ? (col * 8) : (col * 6);
    uint8_t y_page = row;

    while (*str != '\0') {
        OLED_ShowCharEx(x, y_page, *str, size, mode);
        x += step;
        if ((x + step) > OLED_WIDTH) break;
        str++;
    }
}

void OLED_ShowNumAt(uint8_t row, uint8_t col, int32_t num, uint8_t size, uint8_t mode)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%ld", (long)num);
    OLED_ShowStringAt(row, col, buf, size, mode);
}

void OLED_ShowFloatAt(uint8_t row, uint8_t col, float f, uint8_t decimal, uint8_t size, uint8_t mode)
{
    char fmt[8];
    char buf[20];

    if (decimal > 6) decimal = 6;
    snprintf(fmt, sizeof(fmt), "%%.%df", decimal);
    snprintf(buf, sizeof(buf), fmt, (double)f);
    OLED_ShowStringAt(row, col, buf, size, mode);
}


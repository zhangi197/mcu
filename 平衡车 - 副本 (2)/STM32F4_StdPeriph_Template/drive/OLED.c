/* ===================== 底层 GPIO / SPI 操作 ===================== */

static inline void OLED_CS_Low(void)
{
    GPIO_ResetBits(OLED_CS_PORT, OLED_CS_PIN);
}

static inline void OLED_CS_High(void)
{
    GPIO_SetBits(OLED_CS_PORT, OLED_CS_PIN);
}

static inline void OLED_DC_Cmd(void)
{
    GPIO_ResetBits(OLED_DC_PORT, OLED_DC_PIN);
}

static inline void OLED_DC_Data(void)
{
    GPIO_SetBits(OLED_DC_PORT, OLED_DC_PIN);
}

static inline void OLED_RES_Low(void)
{
    GPIO_ResetBits(OLED_RES_PORT, OLED_RES_PIN);
}

static inline void OLED_RES_High(void)
{
    GPIO_SetBits(OLED_RES_PORT, OLED_RES_PIN);
}

static void OLED_DelayMs(uint32_t ms)
{
    /* 简单延时，建议根据系统时钟校准或替换为 HAL_Delay / SysTick */
    volatile uint32_t i, j;
    for (i = 0; i < ms; i++)
        for (j = 0; j < 18600; j++);  /* 约 72MHz 时 1ms，需按实际主频调整 */
}

static void OLED_SPI_WriteByte(uint8_t data)
{
    while (SPI_I2S_GetFlagStatus(OLED_SPI, SPI_I2S_FLAG_TXE) == RESET);
    SPI_I2S_SendData(OLED_SPI, data);
    while (SPI_I2S_GetFlagStatus(OLED_SPI, SPI_I2S_FLAG_BSY) == SET);
}

/* 连续写 len 个字节，CS 保持低电平 */
static void OLED_WriteDataBurst(const uint8_t *data, uint16_t len)
{
    uint16_t i;
    OLED_DC_Data();
    OLED_CS_Low();
    for (i = 0; i < len; i++) {
        while (SPI_I2S_GetFlagStatus(OLED_SPI, SPI_I2S_FLAG_TXE) == RESET);
        SPI_I2S_SendData(OLED_SPI, data[i]);
    }
    while (SPI_I2S_GetFlagStatus(OLED_SPI, SPI_I2S_FLAG_BSY) == SET);
    OLED_CS_High();
}

static void OLED_WriteCommand(uint8_t cmd)
{
    OLED_DC_Cmd();
    OLED_CS_Low();
    OLED_SPI_WriteByte(cmd);
    OLED_CS_High();
}

static void OLED_WriteData(uint8_t data)
{
    OLED_DC_Data();
    OLED_CS_Low();
    OLED_SPI_WriteByte(data);
    OLED_CS_High();
}

static void OLED_SetPos(uint8_t x, uint8_t y_page)
{
    OLED_WriteCommand((uint8_t)(0xB0 + (y_page & 0x07)));
    OLED_WriteCommand((uint8_t)(((x & 0xF0) >> 4) | 0x10));
    OLED_WriteCommand((uint8_t)(x & 0x0F));
}

/* ===================== 初始化 ===================== */

void OLED_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStruct;
    SPI_InitTypeDef  SPI_InitStruct;

    /* 使能时钟 */
    OLED_GPIO_CLK_ENABLE();
    OLED_SPI_CLK_ENABLE();

    /* 配置 CS / DC / RES 为推挽输出 */
    GPIO_InitStruct.GPIO_Pin   = OLED_CS_PIN;
    GPIO_InitStruct.GPIO_Mode  = GPIO_Mode_OUT;
    GPIO_InitStruct.GPIO_OType = GPIO_OType_PP;
    GPIO_InitStruct.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_InitStruct.GPIO_PuPd  = GPIO_PuPd_NOPULL;  
    GPIO_Init(OLED_CS_PORT, &GPIO_InitStruct);

    GPIO_InitStruct.GPIO_Pin = OLED_DC_PIN;
    GPIO_Init(OLED_DC_PORT, &GPIO_InitStruct);

    GPIO_InitStruct.GPIO_Pin = OLED_RES_PIN;
    GPIO_Init(OLED_RES_PORT, &GPIO_InitStruct);

    /* 初始状态 */
    OLED_CS_High();
    OLED_DC_Data();
    OLED_RES_High();

    /* 配置 SPI 引脚 SCK / MOSI（默认引脚，若使用重映射请自行修改） */
#if OLED_USE_SPI1
    GPIO_InitStruct.GPIO_Pin  = GPIO_Pin_5 | GPIO_Pin_7;  /* PA5=SCK, PA7=MOSI */
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_AF;
    GPIO_InitStruct.GPIO_OType = GPIO_OType_PP;
    GPIO_InitStruct.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_InitStruct.GPIO_PuPd = GPIO_PuPd_NOPULL;

    GPIO_Init(GPIOA, &GPIO_InitStruct);
    GPIO_PinAFConfig(GPIOA, GPIO_PinSource5, GPIO_AF_SPI1);
    GPIO_PinAFConfig(GPIOA, GPIO_PinSource7, GPIO_AF_SPI1);
#else
    GPIO_InitStruct.GPIO_Pin  = GPIO_Pin_13 | GPIO_Pin_15;  /* PB13=SCK, PB15=MOSI */
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_AF;
    GPIO_Init(GPIOB, &GPIO_InitStruct);
    GPIO_PinAFConfig(GPIOB, GPIO_PinSource13, GPIO_AF_SPI2);
    GPIO_PinAFConfig(GPIOB, GPIO_PinSource15, GPIO_AF_SPI2);
#endif

    /* 初始化 SPI */
    SPI_InitStruct.SPI_Direction         = SPI_Direction_2Lines_FullDuplex;
    SPI_InitStruct.SPI_Mode              = SPI_Mode_Master;
    SPI_InitStruct.SPI_DataSize          = SPI_DataSize_8b;
    SPI_InitStruct.SPI_CPOL              = SPI_CPOL_High;      /* Mode 3 */
    SPI_InitStruct.SPI_CPHA              = SPI_CPHA_2Edge;
    SPI_InitStruct.SPI_NSS               = SPI_NSS_Soft;
    SPI_InitStruct.SPI_BaudRatePrescaler = SPI_BaudRatePrescaler_4;
    SPI_InitStruct.SPI_FirstBit          = SPI_FirstBit_MSB;
    SPI_InitStruct.SPI_CRCPolynomial     = 7;
    SPI_Init(OLED_SPI, &SPI_InitStruct);
    SPI_Cmd(OLED_SPI, ENABLE);

    /* 硬件复位 */
    OLED_RES_Low();
    OLED_DelayMs(100);
    OLED_RES_High();
    OLED_DelayMs(100);

    /* SSD1306 初始化序列 */
    OLED_WriteCommand(0xAE); /* 显示关闭 */
    OLED_WriteCommand(0x20); OLED_WriteCommand(0x10); /* 页地址模式 */
    OLED_WriteCommand(0xB0); /* 页起始地址 */
    OLED_WriteCommand(0xC8); /* COM 扫描方向：从下到上 */
    OLED_WriteCommand(0x00); /* 低列地址 */
    OLED_WriteCommand(0x10); /* 高列地址 */
    OLED_WriteCommand(0x40); /* 起始行 */
    OLED_WriteCommand(0x81); OLED_WriteCommand(0xCF); /* 对比度 */
    OLED_WriteCommand(0xA1); /* 段重映射 */
    OLED_WriteCommand(0xA6); /* 正常显示 */
    OLED_WriteCommand(0xA8); OLED_WriteCommand(0x3F); /* 复用率 1/64 */
    OLED_WriteCommand(0xA4); /* 输出跟随 RAM */
    OLED_WriteCommand(0xD3); OLED_WriteCommand(0x00); /* 显示偏移 0 */
    OLED_WriteCommand(0xD5); OLED_WriteCommand(0xF0); /* 时钟分频 */
    OLED_WriteCommand(0xD9); OLED_WriteCommand(0x22); /* 预充电周期 */
    OLED_WriteCommand(0xDA); OLED_WriteCommand(0x12); /* COM 引脚配置 */
    OLED_WriteCommand(0xDB); OLED_WriteCommand(0x20); /* VCOMH */
    OLED_WriteCommand(0x8D); OLED_WriteCommand(0x14); /* 使能电荷泵 */
    OLED_WriteCommand(0xAF); /* 显示开启 */
    OLED_DelayMs(100);

    OLED_ClearScreen();
}

/* ===================== GRAM 操作 ===================== */

void OLED_ClearGRAM(void)
{
    memset(OLED_GRAM, 0x00, sizeof(OLED_GRAM));
}

void OLED_FillGRAM(uint8_t color)
{
    uint8_t fill = (color == OLED_COLOR_WHITE) ? 0xFF : 0x00;
    memset(OLED_GRAM, fill, sizeof(OLED_GRAM));
}

void OLED_RefreshGRAM(void)
{
    uint8_t page;
    for (page = 0; page < OLED_PAGES; page++) {
        OLED_SetPos(0, page);
        OLED_WriteDataBurst(OLED_GRAM[page], OLED_WIDTH);
    }
}

void OLED_ClearScreen(void)
{
    OLED_ClearGRAM();
    OLED_RefreshGRAM();
}

void OLED_FillScreen(uint8_t color)
{
    OLED_FillGRAM(color);
    OLED_RefreshGRAM();
}


    OLED_DrawLine(127, 0, 0, 63, OLED_COLOR_WHITE);
    OLED_RefreshGRAM();
    OLED_DelayMs(1500);

    /* 3. 位图 + 大字体 */
    OLED_ClearGRAM();
    OLED_DrawBMP(56, 2, 72, 4, gOLED_DemoIcon16x16);
    OLED_ShowStringAt(3, 3, "I <3 MCU", OLED_FONT_6X8, OLED_MODE_NORMAL);
    OLED_RefreshGRAM();
    OLED_DelayMs(1500);

    /* 4. 8x16 字体演示 */
    OLED_ClearGRAM();
